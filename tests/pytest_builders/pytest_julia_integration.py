class TestTranslationAllModels:
    """Translate every .mdl in test-models; assert the .jl file is created."""

    @pytest.mark.parametrize(
        "folder,mdl_path",
        _all_mdl_files(),
        ids=[f for f, _ in _all_mdl_files()],
    )
    @pytest.mark.filterwarnings("ignore::UserWarning")
    def test_produces_jl_file(self, folder, mdl_path, tmp_path):
        """translate_to_julia() must not raise and must create a .jl file."""
        import shutil as _shutil
        dst = tmp_path / mdl_path.name
        _shutil.copy(mdl_path, dst)

        from pysd import translate_to_julia

        jl_path = translate_to_julia(dst)
        assert jl_path.exists(), f"{folder}: .jl file was not created"
        assert jl_path.suffix == ".jl"

    @pytest.mark.parametrize(
        "folder,mdl_path",
        _all_mdl_files(),
        ids=[f for f, _ in _all_mdl_files()],
    )
    @pytest.mark.filterwarnings("ignore::UserWarning")
    def test_jl_contains_required_sections(self, folder, mdl_path, tmp_path):
        """Generated .jl must contain the structural markers of a valid MTK model."""
        import shutil as _shutil
        dst = tmp_path / mdl_path.name
        _shutil.copy(mdl_path, dst)

        from pysd import translate_to_julia

        jl_path = translate_to_julia(dst)
        content = jl_path.read_text(encoding="utf-8")

        assert "using OrdinaryDiffEq" in content, f"{folder}: missing 'using OrdinaryDiffEq'"
        assert "function rhs!" in content, f"{folder}: missing 'function rhs!'"
        assert "run_model" in content, f"{folder}: missing 'run_model'"
        assert "function observe" in content, f"{folder}: missing 'function observe'"


