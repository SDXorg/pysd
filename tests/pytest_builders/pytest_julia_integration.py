class TestTranslationFeatures:
    """Spot-check that specific SD constructs produce the expected Julia output."""

    def _translate(self, folder: str, tmp_path: Path) -> str:
        import shutil as _shutil
        mdl = next((TEST_MODELS_DIR / folder).glob("*.mdl"))
        dst = tmp_path / mdl.name
        _shutil.copy(mdl, dst)
        from pysd import translate_to_julia
        return translate_to_julia(dst).read_text(encoding="utf-8")

    def test_integ_emits_ode(self, tmp_path):
        content = self._translate("abs", tmp_path)
        assert "du[" in content, "INTEG must produce du[i] = ... ODE derivative"

    def test_lookup_emits_interpolation(self, tmp_path):
        content = self._translate("lookups_inline", tmp_path)
        assert "LinearInterpolation" in content
        assert "DataInterpolations" in content

